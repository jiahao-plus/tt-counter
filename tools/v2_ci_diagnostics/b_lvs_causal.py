"""Part B: causal isolation of R1 / R2 / R3 from the 3rd-round artefacts.

Rules this script obeys:
  * netgen's left|right pairing display is a MATCHING RESULT, not a short.
    We never call a C1|C2 row "a physical short".
  * Every claim is either MEASURED (read from a file) or PREDICTED (a model).
  * 44 = 21+16+0+1+1+5 stays the authoritative accounting; the .rpt row
    counts below are a DIFFERENT accounting and are never summed into it.
"""
import collections
import os
import re

from paths import RUN as BASE
STEP = 0.460
PRUNE = 25.76

RPT = os.path.join(BASE, '66-netgen-lvs/reports/lvs.netgen.rpt')
txt = open(RPT, encoding='utf-8', errors='replace').read()

# ---------------------------------------------------------------- sections
def section(name):
    m = re.search(r'^%s$' % name, txt, re.M)
    return m.start() if m else None


net_sec = section('NET mismatches: Class fragments follow \\(with fanout counts\\):')
dev_sec = section('DEVICE mismatches: Class fragments follow \\(with node fanout counts\\):')
pin_sec = txt.rfind('Subcircuit pins:')
tail = txt.rfind('Final result:')

# ---------------------------------------------------------------- NET rows
net_block = txt[net_sec:dev_sec]
net_rows = re.findall(r'^Net: (\S+)\s*\|(.*)$', net_block, re.M)

# ---------------------------------------------------------------- DEVICE rows
dev_block = txt[dev_sec:tail]
dev_rows = re.findall(r'^Instance: (\S+)\s*\|(.*)$', dev_block, re.M)

# ---------------------------------------------------------------- PIN rows
pin_block = txt[pin_sec:tail]
pin_rows = []
for ln in pin_block.splitlines():
    if '|' not in ln:
        continue
    a, b = ln.split('|', 1)
    a, b = a.strip(), b.strip()
    if not a or a.startswith('Circuit 1') or set(a) <= set('-'):
        continue
    pin_rows.append((a, b))

print('=' * 78)
print('SECTION ROW COUNTS IN lvs.netgen.rpt  (a DIFFERENT accounting from 44)')
print('=' * 78)
print('  NET   rows : %d' % len(net_rows))
print('  DEVICE rows: %d' % len(dev_rows))
print('  PIN   rows : %d' % len(pin_rows))

# ---------------------------------------------------------------- R1 nets
print()
print('=' * 78)
print('R1 -- nets whose C1 name is "<instance>/<pin>" (auto-generated by Magic)')
print('=' * 78)
auto = [(a, b) for a, b in net_rows if '/' in a and not a.startswith('FILLER_')
        and a != 'VGND' and a != 'VPWR']
filler = [(a, b) for a, b in net_rows if a.startswith('FILLER_')]
real = [(a, b) for a, b in net_rows if a in ('VGND', 'VPWR')]

print('  auto-named  <inst>/<pin> : %d  -> %s' % (len(auto), [a for a, _ in auto]))
print('  FILLER_*/VPB             : %d' % len(filler))
print('  power nets               : %d  -> %s' % (len(real), [a for a, _ in real]))

print()
print('  R1 detail (these are NAME losses, not connection losses):')
for a, b in auto:
    print('    %-22s | %s' % (a, b))

# ---------------------------------------------------------------- R1: is _214_/X
# topologically the same net as the reference's pwm_out?
print()
print('=' * 78)
print('R1 -- the _214_/X row: same TOPOLOGY as pwm_out, different NAME?')
print('=' * 78)
m = re.search(r'^Net: _214_/X\s*\|\s*(.*?)(?=^Net: |\Z)', net_block, re.M | re.S)
if m:
    for ln in m.group(1).splitlines():
        if ln.strip():
            print('   C1 member: %s' % ln.strip())
print()
print('   reference pwm_out members (from lvs.netgen.rpt, C2 column of the first row):')
m = re.search(r'^Net: FILLER_53_9/VPB\s*\|Net: pwm_out\s*$(.*?)(?=^Net: )',
              net_block, re.M | re.S)
if m:
    for ln in m.group(1).splitlines():
        if '|' in ln and ln.split('|')[1].strip():
            print('   C2 member:%s' % ln.split('|')[1].rstrip())

# ---------------------------------------------------------------- R2
print()
print('=' * 78)
print('R2 -- every floating VPB/VNB net in C1 and where its cells sit')
print('=' * 78)
floating = [(a, b) for a, b in net_rows if b.strip().startswith('(no matching net)')]
print('  C1 nets with no counterpart: %d' % len(floating))
cat = collections.Counter()
for a, b in floating:
    if a.startswith('FILLER_') and a.endswith('/VPB'):
        cat['FILLER_/VPB (floating body)'] += 1
    elif a.startswith('u_rs_'):
        cat['u_rs_*/net (research macro pin)'] += 1
    elif '/' in a:
        cat['other <inst>/<pin>'] += 1
    else:
        cat['plain name'] += 1
for k, v in cat.items():
    print('    %-34s %d' % (k, v))

# ---------------------------------------------------------------- R2 -> segments
print()
print('=' * 78)
print('R2 -- do the floating-VPB cells sit in PRUNABLE row segments?')
print('=' * 78)
ROW_RE = re.compile(
    r'^ROW\s+(\S+)\s+\S+\s+(-?\d+)\s+(-?\d+)\s+\S+\s+'
    r'DO\s+(\d+)\s+BY\s+1\s+STEP\s+(\d+)', re.M)
CELL_RE = re.compile(
    r'^\s*-\s+(\S+)\s+(sky130_fd_sc_hd__\S+)\s+.*?\(\s*(-?\d+)\s+(-?\d+)\s*\)'
    r'\s+(\S+)\s*;', re.M)

t18 = open(os.path.join(
    BASE, '18-openroad-cutrows/tt_um_jiahao_plus_counter.def'),
    encoding='utf-8', errors='replace').read()
segs = []
for mm in ROW_RE.finditer(t18):
    x, y, n = (int(mm.group(2)) / 1000.0, int(mm.group(3)) / 1000.0,
               int(mm.group(4)))
    segs.append(dict(x0=x, y=y, x1=x + n * STEP, w=n * STEP,
                     prunable=(n * STEP) < PRUNE))

t52 = open(os.path.join(
    BASE, '52-openroad-fillinsertion/tt_um_jiahao_plus_counter.def'),
    encoding='utf-8', errors='replace').read()
place = {}
for mm in CELL_RE.finditer(t52):
    place[mm.group(1)] = (mm.group(2), int(mm.group(3)) / 1000.0,
                          int(mm.group(4)) / 1000.0)


def seg_of(x, y):
    for s in segs:
        if abs(s['y'] - y) < 1e-3 and s['x0'] - 1e-3 <= x < s['x1'] - 1e-3:
            return s
    return None


vpb_nets = [a for a, b in floating if a.startswith('FILLER_') and a.endswith('/VPB')]
rows_needed = set()
for a, b in floating:
    pass

# The FILLER_<r>_<c> name encodes the cell instance; look it up directly.
print('  %-20s %-12s %10s %10s  %s' % ('net', 'cell', 'x', 'y', 'segment'))
nprun = nkeep = nmiss = 0
for nm in vpb_nets:
    stem = nm[:-len('/VPB')]
    if stem in place:
        cls, x, y = place[stem]
        s = seg_of(x, y)
        if s is None:
            nmiss += 1
            tag = 'outside all segments'
        elif s['prunable']:
            nprun += 1
            tag = 'PRUNABLE (w=%.2f)' % s['w']
        else:
            nkeep += 1
            tag = 'KEPT (w=%.2f)' % s['w']
        print('  %-20s %-12s %10.3f %10.3f  %s'
              % (nm, cls.replace('sky130_fd_sc_hd__', ''), x, y, tag))
    else:
        nmiss += 1
        print('  %-20s %-12s %10s %10s  %s' % (nm, '?', '?', '?', 'name not found'))

print()
print('  floating-VPB nets in PRUNABLE segments : %d' % nprun)
print('  floating-VPB nets in KEPT segments     : %d' % nkeep)
print('  unresolved                             : %d' % nmiss)

# ---------------------------------------------------------------- R3
print()
print('=' * 78)
print('R3 -- the two symmetric pins')
print('=' * 78)
for a, b in pin_rows:
    if 'Mismatch' in b or 'no pin' in b:
        print('  C1 %-42s | C2 %s' % (a, b))

# ---------------------------------------------------------------- conclusion guard
print()
print('=' * 78)
print('WHAT THIS SCRIPT DOES *NOT* SAY')
print('=' * 78)
print('  * It never interprets a "Net: A | Net: B" row as A and B being')
print('    shorted.  That row is a matching verdict on two DIFFERENT circuits.')
print('  * It never adds the .rpt row counts to the 44 metric.')
print('  * It cannot re-run Magic or netgen locally (neither is installed).')
